_CRON_CONTROLS = {';', '&&', '||', '|', '&', '(', ')'}
_CRON_REDIRECTS = {'>', '>>', '<', '>&', '<&', '>|', '<<', '<<<'}
_CRON_FD = '\uf000'
_CRON_LITERAL = {character:chr(0xe000+ord(character)) for character in ';&|()<>'}
_CRON_UNSHIELD = str.maketrans({value:key for key,value in _CRON_LITERAL.items()})


def _cron_mentions_sls(value):
    return (any(marker in value for marker in CRON_MARKERS)
            or any(name in value for name in _CRON_SCRIPTS))


def _cron_dynamic_region(command,start):
    if command[start]=='`':
        escaped=False
        for index in range(start+1,len(command)):
            character=command[index]
            if escaped:escaped=False;continue
            if character=='\\':escaped=True;continue
            if character=='`':return command[start:index+1]
        return command[start:]
    depth=1;quote=None;escaped=False;index=start+2
    while index<len(command):
        character=command[index]
        if escaped:escaped=False
        elif character=='\\' and quote!="'":escaped=True
        elif character in ("'",'"'):
            if quote is None:quote=character
            elif quote==character:quote=None
        elif quote is None:
            if character=='(':depth+=1
            elif character==')':
                depth-=1
                if not depth:return command[start:index+1]
        index+=1
    return command[start:]


def _cron_shell_source(command):
    """Keep quote/escape and adjacent descriptor provenance through shlex.

    Input is Latin-1, so the private-use markers cannot collide with input.
    Quoted shell punctuation is data, and only bare adjacent digits select a
    descriptor: ``2>&1`` differs from both ``2 >&1`` and ``'2'>&1``.
    """
    output=[]; quote=None; escaped=False; word=''; word_start=0
    for index,character in enumerate(command):
        if escaped:
            output.append(_CRON_LITERAL.get(character,character)); escaped=False
            word+=character; continue
        if character=='\\' and quote!="'":
            output.append(character); escaped=True; word+=character; continue
        if character in ("'",'"'):
            if quote is None:quote=character
            elif quote==character:quote=None
            output.append(character); word+=character; continue
        if quote!="'" and (character=='`' or command.startswith('$(',index)):
            # Inspect the substitution text without interpreting it. Literal
            # single-quoted substitution syntax remains ordinary data.
            if _cron_mentions_sls(_cron_dynamic_region(command,index)):
                raise RecoveryError('Dynamic SLL cron execution requires administrator review')
        if quote is not None:
            output.append(_CRON_LITERAL.get(character,character)); word+=character; continue
        if character=='#' and not word:break
        if character in '<>' and word.isdecimal():
            output.insert(word_start,_CRON_FD)
        output.append(character)
        if character.isspace() or character in _CRON_LITERAL:
            word=''; word_start=len(output)
        else:word+=character
    return ''.join(output)


def _cron_executable(tokens, account):
    """Classify one simple shell command; never execute or expand its values."""
    arguments=[]; redirects=[]; index=0
    while index<len(tokens):
        token=tokens[index]; descriptor=None
        if token.startswith(_CRON_FD) and token[1:].isdecimal() and index+1<len(tokens) and tokens[index+1] in _CRON_REDIRECTS:
            descriptor=token[1:]; index+=1; token=tokens[index]
        if token in _CRON_REDIRECTS:
            if index+1>=len(tokens):
                raise RecoveryError('Malformed SLL cron redirection requires administrator review')
            redirects.append((descriptor,token,tokens[index+1].translate(_CRON_UNSHIELD))); index+=2
        else:
            arguments.append(token.translate(_CRON_UNSHIELD)); index+=1
    mentioned=any(_cron_mentions_sls(value) for value in arguments)
    while arguments and re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*=.*',arguments[0]):
        arguments.pop(0)
    if not arguments:return False
    # These are the only wrappers generated by supported releases. Unknown
    # execution wrappers are never interpreted as ownership based on operands.
    for _ in range(4):
        if not arguments:return False
        executable=arguments[0]
        if executable in ('exec','/usr/bin/env','/bin/env','env'):
            arguments.pop(0)
            if executable!='exec':
                while arguments:
                    if arguments[0] in ('-i','--ignore-environment'):arguments.pop(0)
                    elif arguments[0] in ('-u','--unset') and len(arguments)>1:
                        del arguments[:2]
                    elif re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*=.*',arguments[0]):arguments.pop(0)
                    elif arguments[0]=='--':arguments.pop(0);break
                    elif arguments[0].startswith('-'):
                        if mentioned:raise RecoveryError('Unrecognized SLL cron environment wrapper requires review')
                        return False
                    else:break
            continue
        if executable in ('/usr/bin/timeout','/bin/timeout','timeout'):
            arguments.pop(0)
            while arguments and arguments[0].startswith('--'):
                if not re.fullmatch(r'--(?:signal=[A-Za-z0-9]+|kill-after=[0-9]+(?:\.[0-9]+)?[smhd]?)',arguments[0]):
                    if mentioned:raise RecoveryError('Unrecognized SLL cron timeout wrapper requires review')
                    return False
                arguments.pop(0)
            if not arguments or not re.fullmatch(r'[0-9]+(?:\.[0-9]+)?[smhd]?',arguments[0]):
                if mentioned:raise RecoveryError('Unrecognized SLL cron timeout requires review')
                return False
            arguments.pop(0);continue
        break
    else:
        if mentioned:raise RecoveryError('SLL cron wrapper depth requires review')
        return False
    if not arguments:return False
    executable=arguments.pop(0)
    if mentioned and (executable in ('.','source','eval','command','builtin') or '$' in executable or '`' in executable):
        raise RecoveryError('Dynamic SLL cron executable requires administrator review')
    interpreter=Path(executable).name
    if interpreter in ('sh','bash','php') or re.fullmatch(r'python3(?:\.[0-9]{1,2})?',interpreter):
        allowed_interpreter=(executable in ('sh','bash','php','/bin/sh','/usr/bin/sh','/bin/bash','/usr/bin/bash','/usr/bin/php')
                             or bool(re.fullmatch(r'(?:/usr/bin/)?python3(?:\.[0-9]{1,2})?',executable)))
        if not allowed_interpreter:
            if mentioned:raise RecoveryError('Unrecognized SLL cron interpreter requires review')
            return False
        flags={'-I','-B','-u'} if interpreter.startswith('python') else ({'-f'} if interpreter=='php' else {'-e','-u'})
        while arguments and arguments[0] in flags:arguments.pop(0)
        if arguments and arguments[0]=='--':arguments.pop(0)
        if not arguments:return False
        if arguments[0].startswith('-'):
            if mentioned:raise RecoveryError('Inline or unrecognized SLL cron execution requires review')
            return False
        executable=arguments.pop(0)
    elif interpreter in ('nice','flock','runuser','su','sudo','sh','bash','env','timeout',
                         'nohup','setsid','xargs','time','stdbuf','ionice','chrt','taskset',
                         'prlimit','setpriv','systemd-run','doas','for','if','while','until','case'):
        if mentioned:raise RecoveryError('Unrecognized SLL cron execution wrapper requires review')
        return False
    if mentioned and ('$' in executable or '`' in executable):
        raise RecoveryError('Dynamic SLL cron script requires administrator review')
    name=Path(executable).name
    owned_path=(executable.startswith(RUNTIME+'/')
                or executable.startswith('/var/www/html/admin/modules/slsmassnotifyserver/bin/')
                or executable.startswith('/var/lib/asterisk/SLS_Mass_Notifications_Plugin/'))
    if account=='root' and name in ('nws_weather_alert.sh','nwsalerts_ensure_menu_patch.sh') and not owned_path:
        # Older user-cron migration owned these names. A separately maintained
        # root menu helper was never part of this module's root job inventory.
        return False
    if not owned_path and name not in _CRON_SCRIPTS:return False
    directories={RUNTIME,'/var/www/html/admin/modules/slsmassnotifyserver/bin','/var/lib/asterisk/bin','/usr/local/bin'}
    if (name not in _CRON_SCRIPTS or Path(executable).parent.as_posix() not in directories
            and executable!='/usr/local/sbin/sign_sls_mass_notify_local_sig.sh'):
        raise RecoveryError('Unknown SLL cron executable requires administrator review')
    if name=='sls_cron_runner.py':
        jobs={'maintenance','update'} if account=='root' else {'weather','scheduling','announcement_reconcile'}
        valid= len(arguments)==1 and arguments[0] in jobs
    elif name=='sls_mass_notify_announcement_worker.php':valid=arguments in ([],['--reconcile'])
    elif name=='sign_sls_mass_notify_local_sig.sh':valid=arguments in ([],['slsmassnotifyserver'],['dashboard'],['framework'])
    else:valid=not arguments
    if not valid:raise RecoveryError('Unknown SLL cron job arguments require administrator review')
    if any(not ((fd in (None,'1') and operation in ('>','>>') and target=='/dev/null')
                or (fd=='2' and operation=='>&' and target=='1')) for fd,operation,target in redirects):
        raise RecoveryError('Unknown SLL cron redirection requires administrator review')
    return True


def sls_cron_job(line, account='root'):
    """Identify actual fixed SLL execution, preserving unrelated cron operands.

    This is ownership classification only. Restoring root execution still
    requires the separate exact signed-release schedule and file approval.
    """
    if not isinstance(line,bytes) or len(line)>65536 or account not in ('root','asterisk'):
        raise RecoveryError('Invalid cron ownership inspection input')
    text=line.decode('latin1').strip()
    if not text or text.startswith('#') or re.match(r'^[A-Za-z_][A-Za-z0-9_]*\s*=',text):return False
    parts=text.split(None,1 if text.startswith('@') else 5)
    expected=2 if text.startswith('@') else 6
    if len(parts)!=expected:
        if _cron_mentions_sls(text):raise RecoveryError('Malformed SLL cron entry requires administrator review')
        return False
    command=parts[-1]
    try:
        lexer=shlex.shlex(_cron_shell_source(command),posix=True,punctuation_chars=';&|()<>')
        lexer.whitespace_split=True
        lexer.commenters=''
        tokens=list(lexer)
    except ValueError as error:
        if _cron_mentions_sls(command):raise RecoveryError('Unparseable SLL cron entry requires administrator review') from error
        return False
    segments=[]; current=[]; compound=False
    for token in tokens:
        if token in _CRON_CONTROLS:
            compound=True
            if current:segments.append(current);current=[]
        else:current.append(token)
    if current:segments.append(current)
    owned=any(_cron_executable(segment,account) for segment in segments)
    if owned and compound:raise RecoveryError('Compound SLL cron execution requires administrator review')
    return owned


