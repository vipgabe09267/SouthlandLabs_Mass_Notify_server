def fingerprint(s):
    return (s.st_dev, s.st_ino, s.st_size, s.st_mtime_ns, s.st_ctime_ns, s.st_nlink)

def root_file(path):
    return (path.startswith(RUNTIME + '/') or path == RUNTIME or path.startswith(TRUST + '/')
            or path in ('/usr/local/bin/slsconsole', '/usr/local/bin/piper')
            or path.startswith('/usr/local/sbin/') or path.startswith('/etc/systemd/')
            or path.startswith('/etc/apache2/') or path.startswith('/etc/logrotate.'))

def safe_piper_link(path, target):
    relative=path.removeprefix(RUNTIME+'/piper/')
    relative=re.sub(r'^\.replacement-[a-f0-9]{24}/','',relative)
    return (relative=='venv/lib64' and target=='lib') or (bool(re.fullmatch(r'venv/bin/python(?:3(?:\.[0-9]{1,2})?)?',relative)) and bool(re.fullmatch(r'(?:/usr/bin/)?python3(?:\.[0-9]{1,2})?',target)))

def allowed(path):
    if not isinstance(path,str) or str(Path(path)) != path or '..' in Path(path).parts or any(ord(c)<32 or ord(c)==127 for c in path): return False
    try:
        if len(path.encode('utf-8', errors='strict')) > 4096: return False
    except UnicodeEncodeError: return False
    return path in FIXED or path in LINKS or any(path == p or path.startswith(p + '/') for p in TREES)

def strict_json(raw):
    def pairs(values):
        result={}
        for key,value in values:
            if key in result: raise RecoveryError('Duplicate member in recovery JSON')
            result[key]=value
        return result
    def invalid_number(_value): raise RecoveryError('Non-integer number in recovery JSON')
    try:
        text=raw.decode('utf-8',errors='strict') if isinstance(raw,bytes) else raw
        return json.loads(text,object_pairs_hook=pairs,parse_float=invalid_number,parse_constant=invalid_number)
    except (json.JSONDecodeError,UnicodeDecodeError,RecursionError) as error:
        raise RecoveryError('Invalid recovery JSON') from error

class Recovery:
    def __init__(self, snapshot, prefix='/', cron=None, command=None, user_cron=None, approval=None, cron_lock=native_cron_lock):
        self.snapshot=Path(snapshot)
        self.prefix=Path(prefix)
        account=pwd.getpwnam('asterisk')
        self.uid=account.pw_uid
        self.gid=account.pw_gid
        self.cron=cron or (lambda body=None:self.coordinated_system_cron(body,'root'))
        self.user_cron=user_cron or (lambda body=None:self.coordinated_system_cron(body,'asterisk'))
        self.cron_lock=cron_lock
        self._cron_lock_depth=0
        self._cron_lease=None
        self.command=command or self.system_command
        self.total=0
        self.approval=Path(approval) if approval is not None else None
        if not self.snapshot.is_absolute() or '..' in self.snapshot.parts: raise RecoveryError('Snapshot path must be canonical and absolute')

    @contextmanager
    def cron_guard(self):
        if self._cron_lock_depth:
            if self._cron_lease is not None:self._cron_lease.check()
            self._cron_lock_depth+=1
            try:yield
            finally:self._cron_lock_depth-=1
            return
        with self.cron_lock(('root','asterisk')) as lease:
            self._cron_lock_depth=1;self._cron_lease=lease
            try:yield
            finally:self._cron_lock_depth=0;self._cron_lease=None

    def coordinated_system_cron(self,body,user):
        if not self._cron_lock_depth:
            raise RecoveryError('Native cron access requires its shared account coordination')
        if self._cron_lease is not None:self._cron_lease.check()
        result=self.system_cron(body,user)
        if self._cron_lease is not None:self._cron_lease.check()
        return result

    @staticmethod
    def directory(path, protected=False, create=False):
        path = Path(path)
        if not path.is_absolute():
            raise RecoveryError('Descriptor walk path must be absolute')
        fd=os.open('/', os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW|os.O_CLOEXEC)
        try:
            for part in path.parts[1:]:
                if create:
                    try: os.mkdir(part, 0o755, dir_fd=fd)
                    except FileExistsError: pass
                child=os.open(part,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW|os.O_CLOEXEC,dir_fd=fd)
                os.close(fd); fd=child
                s=os.fstat(fd)
                if protected and (s.st_uid != 0 or (s.st_mode & 0o022 and not s.st_mode & stat.S_ISVTX)):
                    raise RecoveryError('Unprotected root recovery/runtime ancestor: ' + str(path))
            result,fd=fd,-1
            return result
        finally:
            if fd>=0: os.close(fd)

    def dest(self,path): return self.prefix.joinpath(*Path(path).parts[1:])

    def static_mode_allowed(self,path,uid,gid,mode):
        if mode & 0o002:
            return False
        if not mode & 0o020:
            return True
        # FreePBX chown uses 0775/0664 for its Asterisk-managed web/config
        # files. These snapshots never authorize root execution. Root runtime,
        # signing/trust files and the Piper compatibility tree stay private.
        return (uid in (0,self.uid) and gid == self.gid and not root_file(path)
                and path != COMPAT and not path.startswith(COMPAT+'/'))

    @staticmethod
    def read_at(parent,name,limit,protected=False):
        fd=os.open(name,os.O_RDONLY|os.O_NOFOLLOW|os.O_NONBLOCK|os.O_CLOEXEC,dir_fd=parent)
        try:
            before=os.fstat(fd)
            if not stat.S_ISREG(before.st_mode) or before.st_nlink!=1 or before.st_size>limit:
                raise RecoveryError('Unsafe, linked or oversized recovery file: '+name)
            if protected and (before.st_uid!=0 or before.st_mode&0o022): raise RecoveryError('Unprotected recovery source: '+name)
            body=bytearray()
            while len(body)<=limit:
                chunk=os.read(fd,min(1024*1024,limit+1-len(body)))
                if not chunk: break
                body.extend(chunk)
            after=os.fstat(fd); current=os.stat(name,dir_fd=parent,follow_symlinks=False)
            if len(body)>limit or fingerprint(before)!=fingerprint(after) or fingerprint(after)!=fingerprint(current):
                raise RecoveryError('Recovery source changed during read: '+name)
            return bytes(body),before
        finally: os.close(fd)

    @staticmethod
    def write_at(parent,name,body,mode=0o600,uid=0,gid=0):
        temp='.sls-recovery-'+uuid.uuid4().hex
        try:
            fd=os.open(temp,os.O_WRONLY|os.O_CREAT|os.O_EXCL|os.O_NOFOLLOW|os.O_CLOEXEC,0o600,dir_fd=parent)
            try:
                view=memoryview(body)
                while view:
                    n=os.write(fd,view)
                    if n<=0: raise RecoveryError('Short recovery write')
                    view=view[n:]
                os.fchown(fd,uid,gid); os.fchmod(fd,mode); os.fsync(fd)
            finally: os.close(fd)
            os.replace(temp,name,src_dir_fd=parent,dst_dir_fd=parent); os.fsync(parent)
        finally:
            try: os.unlink(temp,dir_fd=parent)
            except FileNotFoundError: pass

    @staticmethod
    def system_cron(body=None,user='root'):
        if user not in ('root','asterisk') or body is not None and (not isinstance(body,bytes) or len(body)>1024*1024):
            raise RecoveryError('Invalid recovery crontab account or size')
        args=['/usr/bin/crontab','-u',user]+(['-l'] if body is None else ['-'])
        # crontab output is bounded on both read and write; no shell interpolation.
        import tempfile
        with tempfile.TemporaryFile() as output, tempfile.TemporaryFile() as diagnostic:
            result=subprocess.run(args,input=body,stdout=output,stderr=diagnostic,timeout=15,
                close_fds=True,env={'PATH':'/usr/sbin:/usr/bin:/sbin:/bin','LANG':'C'})
            if output.tell()>1024*1024 or diagnostic.tell()>65536:
                raise RecoveryError('The '+user+' crontab exceeds its recovery inspection bound')
            output.seek(0);value=output.read()
            diagnostic.seek(0);message=diagnostic.read()
        if (body is None and result.returncode==1 and not value
                and message.strip()==('no crontab for '+user).encode()):return b''
        if result.returncode or message or body is not None and value:
            raise RecoveryError('The '+user+' crontab operation failed or returned unexpected diagnostics')
        return value

    @staticmethod
    def system_command(args,check=True):
        import tempfile
        with tempfile.TemporaryFile() as output:
            result=subprocess.run(args,stdout=output,stderr=output,timeout=45,env={'PATH':'/usr/sbin:/usr/bin:/sbin:/bin','LANG':'C'})
            if output.tell()>1024*1024: raise RecoveryError('Recovery service command exceeded output bound')
            output.seek(0); body=output.read()
        if check and result.returncode: raise RecoveryError('Fixed recovery service command failed: '+args[0])
        return body.decode('utf-8',errors='strict').strip()

    def capture_service_state(self):
        output=self.command(['/usr/bin/systemctl','show',SERVICE,'--property=LoadState,UnitFileState,ActiveState'])
        values=dict(line.split('=',1) for line in output.splitlines() if '=' in line)
        state={'enabled':'not-found' if values.get('LoadState')=='not-found' else values.get('UnitFileState'),
               'active':values.get('ActiveState')}
        self.valid_service_state(state)
        return state

    @staticmethod
    def valid_service_state(state):
        if (not isinstance(state,dict) or set(state)!={'enabled','active'}
            or state['enabled'] not in ('enabled','disabled','static','indirect','enabled-runtime','masked','masked-runtime','not-found')
            or state['active'] not in ('active','inactive','failed','unknown')):
            raise RecoveryError('Collector service state is transitional or unrecognized; retry after it stabilizes')

    def service_state(self):
        return {'ok':True,'service':SERVICE,'service_state':self.load()['service_state'],'automatic_activation_safe':False}

    def preflight_services(self):
        """Reject states that cannot be restored before starting a transaction."""
        state = self.capture_service_state()
        if state['enabled'] not in ('enabled', 'disabled', 'not-found'):
            raise RecoveryError('Collector service is ' + state['enabled'] + '. Review its administrator-managed enable or mask state before installation; no SLL runtime or service was changed.')
        if state['enabled'] != 'not-found':
            parent = self.directory(self.dest('/etc/systemd/system').absolute(), protected=True)
            try: body, _ = self.read_at(parent, SERVICE, MAX_FILE, True)
            finally: os.close(parent)
            if body not in SUPPORTED_UNITS:
                raise RecoveryError('Collector service differs from the supported recovery unit. Review its customizations before installation; no service was changed.')
            output = self.command(['/usr/bin/systemctl', 'show', SERVICE, '--property=DropInPaths'])
            if output.strip() != 'DropInPaths=':
                raise RecoveryError('Collector service has administrator overrides. Review those overrides before installation; rollback cannot safely discard them.')
        return {'ok': True, 'service_state': state, 'rollback_supported': True}

    @_serialized_cron
    def preflight_inventory(self):
        records={};self.total=0
        for path in (*TREES,*FIXED,*LINKS):self.inspect(path,records=records)
        for account,backend in (('root',self.cron),('asterisk',self.user_cron)):
            body=backend()
            if len(body)>1024*1024:raise RecoveryError('Current crontab exceeds recovery bound')
            for line in body.splitlines():sls_cron_job(line,account)
        return {'ok':True,'read_only':True,'static_entries':len(records),'static_bytes':self.total}

    def restore_services(self):
        self.verify()
        state=self.load()['service_state']
        if state['enabled'] not in ('enabled','disabled','not-found'):
            raise RecoveryError('Prior collector enable state needs explicit manual recovery')
        unitpath='/etc/systemd/system/'+SERVICE
        if state['enabled']!='not-found':
            parent=self.directory(self.dest(unitpath).parent,protected=True)
            try: unit,_=self.read_at(parent,SERVICE,MAX_FILE,True)
            finally: os.close(parent)
            if unit not in SUPPORTED_UNITS: raise RecoveryError('Prior collector unit is not the fixed unprivileged recovery unit; manual activation required')
        self.command(['/usr/bin/systemctl','daemon-reload'])
        if state['enabled']!='not-found':
            loaded=self.command(['/usr/bin/systemctl','show',SERVICE,'--property=User,Group,FragmentPath,DropInPaths'])
            properties=dict(line.split('=',1) for line in loaded.splitlines() if '=' in line)
            expected={'User':'asterisk','Group':'asterisk','FragmentPath':unitpath,'DropInPaths':''}
            if properties!=expected: raise RecoveryError('Loaded collector unit contains unexpected identity, fragment or overrides')
            self.command(['/usr/bin/systemctl','enable' if state['enabled']=='enabled' else 'disable',SERVICE])
        self.command(['/usr/bin/systemctl','restart' if state['active']=='active' else 'stop',SERVICE],state['enabled']!='not-found')
        actual=self.capture_service_state()
        if actual['enabled']!=state['enabled'] or (actual['active']=='active')!=(state['active']=='active'):
            raise RecoveryError('Collector process/enable-state recovery did not satisfy prior state')
        self.command(['/usr/sbin/apache2ctl','configtest'])
        self.command(['/usr/bin/systemctl','reload','apache2'])
        return {'ok':True,'collector_state_restored':True,'apache_reloaded':True,'automatic_activation_safe':False}

    def inspect(self,path,blobfd=None,records=None):
        if not allowed(path): raise RecoveryError('Path outside fixed recovery inventory')
        if records is not None and len(records)>=MAX_FILES: raise RecoveryError('Static snapshot exceeds entry bound')
        target=self.dest(path)
        try: parent=self.directory(target.parent,protected=root_file(path))
        except FileNotFoundError:
            if records is not None: records[path]={'kind':'absent'}
            return
        try:
            try: s=os.stat(target.name,dir_fd=parent,follow_symlinks=False)
            except FileNotFoundError:
                if records is not None: records[path]={'kind':'absent'}
                return
            if (s.st_uid not in (0,self.uid) or not 0 <= s.st_gid <= MAX_POSIX_ID
                    or (not stat.S_ISLNK(s.st_mode) and not self.static_mode_allowed(path,s.st_uid,s.st_gid,s.st_mode))
                    or (root_file(path) and s.st_uid!=0)):
                raise RecoveryError('Untrusted ownership/mode in static inventory: '+path
                                    +f' (uid={s.st_uid}, gid={s.st_gid}, mode={stat.S_IMODE(s.st_mode):04o})')
            if path not in TREES and s.st_dev!=os.fstat(parent).st_dev: raise RecoveryError('Mounted child in static inventory: '+path)
            entry={'uid':s.st_uid,'gid':s.st_gid,'mode':stat.S_IMODE(s.st_mode)}
            if s.st_mode&0o7000: raise RecoveryError('Special permissions in static inventory: '+path)
            if path == COMPAT or path.startswith(COMPAT + '/'):
                if path not in (COMPAT, COMPAT + '/bin', COMPAT + '/bin/piper'):
                    raise RecoveryError('Unknown Piper compatibility contents; legacy executable environments are not adopted')
                if path != COMPAT + '/bin/piper' and (not stat.S_ISDIR(s.st_mode) or s.st_mode & 0o022):
                    raise RecoveryError('Unsafe Piper compatibility directory')
            if stat.S_ISDIR(s.st_mode):
                if path not in TREES and not any(path.startswith(p+'/') for p in TREES): raise RecoveryError('Expected fixed file, found directory: '+path)
                entry['kind']='dir'
                child=os.open(target.name,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW|os.O_CLOEXEC,dir_fd=parent)
                try:
                    names=sorted(os.listdir(child))
                    if (os.fstat(child).st_dev,os.fstat(child).st_ino)!=(s.st_dev,s.st_ino): raise RecoveryError('Directory changed during snapshot')
                    if len(names)>MAX_FILES: raise RecoveryError('Static directory exceeds entry bound')
                    if records is not None: records[path]=entry
                    for name in names: self.inspect(path+'/'+name,blobfd,records)
                    if fingerprint(s)!=fingerprint(os.stat(target.name,dir_fd=parent,follow_symlinks=False)):
                        raise RecoveryError('Directory changed during snapshot: '+path)
                finally: os.close(child)
                return
            if stat.S_ISREG(s.st_mode):
                body,opened=self.read_at(parent,target.name,MAX_FILE,root_file(path))
                if fingerprint(s)!=fingerprint(opened): raise RecoveryError('File replaced during snapshot')
                self.total+=len(body)
                if self.total>MAX_TOTAL: raise RecoveryError('Static snapshot exceeds 2 GiB bound')
                digest=hashlib.sha256(body).hexdigest()
                entry.update(kind='file',sha256=digest,size=len(body))
                if blobfd is not None:
                    try: os.stat(digest,dir_fd=blobfd,follow_symlinks=False)
                    except FileNotFoundError: self.write_at(blobfd,digest,body)
            elif stat.S_ISLNK(s.st_mode):
                link=os.readlink(target.name,dir_fd=parent)
                if path in LINKS:
                    if link!=LINKS[path]: raise RecoveryError('Unexpected fixed symlink target: '+path)
                elif not path.startswith(RUNTIME+'/piper/'):
                    if path == COMPAT + '/bin/piper' and link == '/usr/local/bin/piper': pass
                    elif path == '/usr/local/bin/piper' and s.st_uid == 0 and link in (RUNTIME + '/piper/venv/bin/piper', COMPAT + '/bin/piper'): pass
                    else: raise RecoveryError('Unexpected symlink in static inventory: '+path)
                elif s.st_uid!=0 or not safe_piper_link(path,link):
                    raise RecoveryError('Unsafe Piper symlink')
                if fingerprint(s)!=fingerprint(os.stat(target.name,dir_fd=parent,follow_symlinks=False)):
                    raise RecoveryError('Symlink changed during snapshot')
                entry.update(kind='link',target=link)
            else: raise RecoveryError('Special file in static recovery inventory: '+path)
            if records is not None:
                records[path]=entry
                if len(records)>MAX_FILES: raise RecoveryError('Static snapshot exceeds entry bound')
        finally: os.close(parent)

    @_serialized_cron
    def snapshot_create(self):
        parent=self.directory(self.snapshot.parent,protected=True)
        try:
            owner=os.fstat(parent)
            if owner.st_uid!=0 or stat.S_IMODE(owner.st_mode)!=0o700: raise RecoveryError('Recovery parent must be root-owned mode 0700')
            try: os.stat(self.snapshot.name,dir_fd=parent,follow_symlinks=False)
            except FileNotFoundError: pass
            else: raise RecoveryError('Original snapshot already exists; refusing replacement')
            stage='.static-building-'+uuid.uuid4().hex
            os.mkdir(stage,0o700,dir_fd=parent)
            stagefd=os.open(stage,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=parent)
            try:
                os.mkdir('blobs',0o700,dir_fd=stagefd)
                blobs=os.open('blobs',os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=stagefd)
                try:
                    records={}; self.total=0
                    for path in (*TREES,*FIXED,*LINKS): self.inspect(path,blobs,records)
                    cron=self.cron()
                    if len(cron)>1024*1024: raise RecoveryError('Root crontab exceeds recovery bound')
                    self.write_at(stagefd,'root-cron.original',cron)
                    user_cron=self.user_cron()
                    if len(user_cron)>1024*1024: raise RecoveryError('Asterisk crontab exceeds recovery bound')
                    self.write_at(stagefd,'asterisk-cron.original',user_cron)
                    manifest={'schema':1,'records':records,'cron_sha256':hashlib.sha256(cron).hexdigest(),'user_cron_sha256':hashlib.sha256(user_cron).hexdigest(),'automatic_activation_safe':False,'service_state':self.capture_service_state()}
                    if self.approval is not None:
                        approval_parent=self.directory(self.approval.parent,protected=True)
                        try: raw,_=self.read_at(approval_parent,self.approval.name,MAX_MANIFEST,True)
                        finally: os.close(approval_parent)
                        approval=strict_json(raw)
                        self.validate_activation_approval(approval,records,cron)
                        manifest['previous_activation_approval']=approval
                    self.write_at(stagefd,'manifest.json',json.dumps(manifest,sort_keys=True,separators=(',',':')).encode())
                    os.fsync(blobs); os.fsync(stagefd)
                finally: os.close(blobs)
            finally: os.close(stagefd)
            # Original private snapshot is never replaced; failed stage is retained.
            os.rename(stage,self.snapshot.name,src_dir_fd=parent,dst_dir_fd=parent); os.fsync(parent)
        finally: os.close(parent)
        return {'ok':True,'snapshot':str(self.snapshot),'automatic_activation_safe':False}

    def load(self):
        fd=self.directory(self.snapshot,protected=True)
        try:
            if stat.S_IMODE(os.fstat(fd).st_mode)!=0o700: raise RecoveryError('Snapshot must remain root-only')
            raw,_=self.read_at(fd,'manifest.json',MAX_MANIFEST,True)
            manifest=strict_json(raw)
            if not isinstance(manifest,dict): raise RecoveryError('Invalid static manifest')
            records=manifest.get('records')
            self.valid_service_state(manifest.get('service_state'))
            expected_manifest={'schema','records','cron_sha256','user_cron_sha256','automatic_activation_safe','service_state'}
            if 'previous_activation_approval' in manifest: expected_manifest.add('previous_activation_approval')
            if (set(manifest)!=expected_manifest or type(manifest.get('schema')) is not int or manifest['schema']!=1
                    or manifest.get('automatic_activation_safe') is not False or not isinstance(records,dict) or len(records)>MAX_FILES
                    or not re.fullmatch('[a-f0-9]{64}',str(manifest.get('cron_sha256','')))
                    or not re.fullmatch('[a-f0-9]{64}',str(manifest.get('user_cron_sha256','')))):
                raise RecoveryError('Invalid static manifest')
            if not all(p in records for p in (*TREES,*FIXED,*LINKS)): raise RecoveryError('Incomplete fixed inventory')
            blobs=os.open('blobs',os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=fd)
            try:
                bstat=os.fstat(blobs)
                if bstat.st_uid!=0 or stat.S_IMODE(bstat.st_mode)!=0o700: raise RecoveryError('Unprotected recovery blobs')
                total=0
                for path,entry in records.items():
                    if not allowed(path) or not isinstance(entry,dict) or entry.get('kind') not in ('absent','file','dir','link'): raise RecoveryError('Invalid recovery entry')
                    expected={'absent':{'kind'},'dir':{'kind','uid','gid','mode'},'file':{'kind','uid','gid','mode','sha256','size'},'link':{'kind','uid','gid','mode','target'}}[entry['kind']]
                    if set(entry)!=expected: raise RecoveryError('Unexpected recovery entry members')
                    if entry['kind']=='absent': continue
                    if (type(entry.get('uid')) is not int or entry['uid'] not in (0,self.uid)
                            or type(entry.get('gid')) is not int or not 0 <= entry['gid'] <= MAX_POSIX_ID
                            or type(entry.get('mode')) is not int or entry['mode']<0 or entry['mode']&~0o777):
                        raise RecoveryError('Invalid recovery ownership/mode')
                    if entry['kind']!='link' and not self.static_mode_allowed(path,entry['uid'],entry['gid'],entry['mode']):
                        raise RecoveryError('Writable static recovery record')
                    if root_file(path) and entry['uid']!=0: raise RecoveryError('Unsafe root runtime record')
                    if entry['kind']=='file':
                        digest=entry.get('sha256','')
                        if (not isinstance(digest,str) or not re.fullmatch('[a-f0-9]{64}',digest)
                                or type(entry.get('size')) is not int or entry['size']<0 or entry['size']>MAX_FILE): raise RecoveryError('Invalid blob identity')
                        body,_=self.read_at(blobs,digest,MAX_FILE,True); total+=len(body)
                        if total>MAX_TOTAL or len(body)!=entry.get('size') or hashlib.sha256(body).hexdigest()!=digest: raise RecoveryError('Recovery blob verification failed')
                    if entry['kind']=='link':
                        target=entry.get('target')
                        try: target_bytes=target.encode('utf-8',errors='strict') if isinstance(target,str) else b''
                        except UnicodeEncodeError: target_bytes=b''
                        if not target_bytes or len(target_bytes)>4096 or any(ord(c)<32 or ord(c)==127 for c in target): raise RecoveryError('Invalid recovery link')
                        if path in LINKS:
                            if target!=LINKS[path]: raise RecoveryError('Invalid fixed recovery link')
                        elif path == COMPAT + '/bin/piper' and target == '/usr/local/bin/piper': pass
                        elif path == '/usr/local/bin/piper' and entry['uid'] == 0 and target in (RUNTIME + '/piper/venv/bin/piper', COMPAT + '/bin/piper'): pass
                        elif not safe_piper_link(path,target) or entry['uid']!=0: raise RecoveryError('Invalid recovery symlink path')
                    if entry['kind']=='dir' and not any(path==p or path.startswith(p+'/') for p in TREES): raise RecoveryError('Invalid recovery directory')
                cron,_=self.read_at(fd,'root-cron.original',1024*1024,True)
                if hashlib.sha256(cron).hexdigest()!=manifest.get('cron_sha256'): raise RecoveryError('Original root cron verification failed')
                if 'previous_activation_approval' in manifest:
                    self.validate_activation_approval(manifest['previous_activation_approval'],records,cron)
                user_cron,_=self.read_at(fd,'asterisk-cron.original',1024*1024,True)
                if hashlib.sha256(user_cron).hexdigest()!=manifest.get('user_cron_sha256'): raise RecoveryError('Original asterisk cron verification failed')
            finally: os.close(blobs)
            return manifest
        finally: os.close(fd)

    def remove(self,path):
        self.removed+=1
        if self.removed>MAX_FILES: raise RecoveryError('Static removal exceeds entry bound')
        target=self.dest(path)
        try: parent=self.directory(target.parent,protected=root_file(path))
        except FileNotFoundError: return
        try:
            try: s=os.stat(target.name,dir_fd=parent,follow_symlinks=False)
            except FileNotFoundError: return
            if stat.S_ISDIR(s.st_mode):
                child=os.open(target.name,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=parent)
                try:
                    names=os.listdir(child)
                    if len(names)>MAX_FILES: raise RecoveryError('Static removal directory exceeds entry bound')
                finally: os.close(child)
                for name in names: self.remove(path+'/'+name)
                os.rmdir(target.name,dir_fd=parent)
            else:
                if not (stat.S_ISREG(s.st_mode) and s.st_nlink==1) and not stat.S_ISLNK(s.st_mode): raise RecoveryError('Unsafe replacement encountered during recovery')
                os.unlink(target.name,dir_fd=parent)
            os.fsync(parent)
        finally: os.close(parent)

    def original_user_jobs(self):
        fd=self.directory(self.snapshot,protected=True)
        try: body,_=self.read_at(fd,'asterisk-cron.original',1024*1024,True)
        finally: os.close(fd)
        return [line for line in body.splitlines() if sls_user_job(line)]

    @staticmethod
    def validate_activation_approval(approval, records, cron):
        if (not isinstance(approval,dict) or type(approval.get('schema')) is not int or approval['schema']!=1
                or approval.get('source') not in ('publisher-verified-previous-release','fresh-install')
                or not isinstance(approval.get('files'),dict) or not isinstance(approval.get('root_jobs'),list)):
            raise RecoveryError('Missing or invalid prior execution approval; maintenance remains unchanged')
        if approval['source'] == 'publisher-verified-previous-release':
            if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+(?:-beta)?',str(approval.get('version',''))) or not re.fullmatch('[a-f0-9]{64}',str(approval.get('archive_sha256',''))):
                raise RecoveryError('Previous execution approval lacks signed-release identity')
        elif approval['files'] or approval['root_jobs']:
            raise RecoveryError('Fresh installation cannot approve previous root jobs')
        for path, digest in approval['files'].items():
            entry=records.get(path,{})
            if (not isinstance(path,str) or not (path.startswith(RUNTIME + '/') or path in ('/usr/local/sbin/sign_sls_mass_notify_local_sig.sh','/usr/local/bin/slsconsole'))
                    or not re.fullmatch('[a-f0-9]{64}',str(digest)) or entry.get('kind')!='file' or entry.get('sha256')!=digest
                    or entry.get('uid')!=0 or entry.get('mode',0)&0o022):
                raise RecoveryError('Previous root execution differs from its authenticated approval: ' + str(path))
        original=[line.decode('ascii') for line in cron.splitlines() if sls_cron_job(line)]
        if approval['root_jobs']!=original or any(not isinstance(line,str) or '\n' in line or '\r' in line for line in original):
            raise RecoveryError('Previous maintenance schedule changed after approval')
        for line in original:
            runner = re.fullmatch(r'(?:\* \* \* \* \* /usr/bin/python3 -I '+re.escape(RUNTIME)+r'/sls_cron_runner\.py (maintenance)|17 \* \* \* \* /usr/bin/python3 -I '+re.escape(RUNTIME)+r'/sls_cron_runner\.py (update)) >/dev/null 2>&1', line)
            if not runner and not re.fullmatch(r'(?:\* \* \* \* \* /usr/bin/timeout 900 '+re.escape(RUNTIME)+r'/sls_mass_notify_maintenance\.sh|17 (?:\*|\*/6) \* \* \* /usr/bin/timeout 1800 '+re.escape(RUNTIME)+r'/sls_mass_notify_update\.sh)',line):
                raise RecoveryError('Previous maintenance entry is outside the fixed recovery allowlist')
            if runner and RUNTIME + '/sls_cron_runner.py' not in approval['files']:
                raise RecoveryError('Previous cron runner lacks authenticated source approval')
            maintenance = runner.group(1) is not None if runner else line.endswith('sls_mass_notify_maintenance.sh')
            script=RUNTIME+'/'+('sls_mass_notify_maintenance.sh' if maintenance else 'sls_mass_notify_update.sh')
            if script not in approval['files']: raise RecoveryError('Previous root job lacks authenticated source approval')

    @_serialized_cron
    def restore_maintenance(self):
        self.verify()
        manifest=self.load()
        approval=manifest.get('previous_activation_approval')
        if approval is None:
            raise RecoveryError('Previous root runtime was not approved before installation; maintenance remains disabled')
        descriptor=self.directory(self.snapshot,protected=True)
        try:
            original,_=self.read_at(descriptor,'root-cron.original',1024*1024,True)
            self.validate_activation_approval(approval,manifest['records'],original)
            current=self.cron()
            if len(current)>1024*1024: raise RecoveryError('Current root schedule exceeds recovery bound')
            unrelated=[line for line in current.splitlines() if not sls_cron_job(line)]
            body=b'\n'.join(unrelated+[line.encode('ascii') for line in approval['root_jobs']])
            if body: body+=b'\n'
            if len(body)>1024*1024: raise RecoveryError('Recovered root schedule exceeds recovery bound')
            # Persist intent first so a interrupted cron write can be verified/retried.
            self.write_at(descriptor,'maintenance-restored.json',b'{"schema":1,"previous_release_approved":true}')
            if body!=current: self.cron(body)
            self.verify()
        finally: os.close(descriptor)
        return {'ok':True,'previous_maintenance_restored':True,'previous_release_approved':True}

    @_serialized_cron
    def restore_user_jobs(self,disable=False,current=None):
        current=self.user_cron() if current is None else current
        if len(current)>1024*1024: raise RecoveryError('Current asterisk crontab exceeds recovery bound')
        unrelated=[line for line in current.splitlines() if not sls_user_job(line)]
        jobs=[] if disable else self.original_user_jobs()
        replacement=b'\n'.join(unrelated+jobs)
        if replacement: replacement+=b'\n'
        if len(replacement)>1024*1024: raise RecoveryError('Restored asterisk crontab exceeds recovery bound')
        if replacement!=current: self.user_cron(replacement)

    @_serialized_cron
    def restore(self):
        manifest=self.load(); records=manifest['records']
        # Preflight every current destination before any restore mutation.
        current={}; self.total=0
        for path in (*TREES,*FIXED,*LINKS): self.inspect(path,records=current)
        current_cron=self.cron();current_user_cron=self.user_cron()
        if len(current_cron)>1024*1024 or len(current_user_cron)>1024*1024:
            raise RecoveryError('Current crontab exceeds recovery bound')
        # Validate both accounts before changing either schedule or a static
        # file. An unknown actual SLL command cannot be silently adopted or
        # removed; path references in unrelated backup/checksum jobs survive.
        safe_lines=[line for line in current_cron.splitlines() if not sls_cron_job(line)]
        for line in current_user_cron.splitlines():sls_user_job(line)
        self.original_user_jobs()
        snapfd=self.directory(self.snapshot,protected=True)
        try:
            blobs=os.open('blobs',os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=snapfd)
            try:
                # Do not revive legacy root PHP/module bootstrap jobs. Preserve current
                # unrelated jobs, including administrator changes made during upgrade.
                safe=b'\n'.join(safe_lines)
                safe=(safe+b'\n') if safe else b''
                if safe!=current_cron: self.cron(safe)
                try: os.unlink('maintenance-restored.json',dir_fd=snapfd)
                except FileNotFoundError: pass
                os.fsync(snapfd)
                self.restore_user_jobs(disable=True,current=current_user_cron)
                self.write_at(snapfd,'restore-started.json',b'{"automatic_activation_safe":false,"state":"restoring"}')
                self.removed=0
                for path in sorted(current,key=lambda p:(p.count('/'),p),reverse=True):
                    if current[path]['kind']!='absent' and (path not in records or records[path]['kind']=='absent' or records[path]['kind']!=current[path]['kind']): self.remove(path)
                for path,entry in sorted(records.items(),key=lambda item:(item[0].count('/'),item[0])):
                    kind=entry['kind']
                    if kind=='absent': continue
                    target=self.dest(path); parent=self.directory(target.parent,protected=root_file(path),create=True)
                    try:
                        if kind=='dir':
                            try: os.mkdir(target.name,entry['mode'],dir_fd=parent)
                            except FileExistsError: pass
                            child=os.open(target.name,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=parent)
                            try: os.fchown(child,entry['uid'],entry['gid']); os.fchmod(child,entry['mode']); os.fsync(child)
                            finally: os.close(child)
                        elif kind=='file':
                            body,_=self.read_at(blobs,entry['sha256'],MAX_FILE,True)
                            if hashlib.sha256(body).hexdigest()!=entry['sha256']: raise RecoveryError('Recovery blob changed')
                            self.write_at(parent,target.name,body,entry['mode'],entry['uid'],entry['gid'])
                        else:
                            try: old=os.stat(target.name,dir_fd=parent,follow_symlinks=False)
                            except FileNotFoundError: old=None
                            if old is not None:
                                if not stat.S_ISLNK(old.st_mode): raise RecoveryError('Link destination changed during restore')
                                os.unlink(target.name,dir_fd=parent)
                            os.symlink(entry['target'],target.name,dir_fd=parent)
                            os.chown(target.name,entry['uid'],entry['gid'],dir_fd=parent,follow_symlinks=False)
                        os.fsync(parent)
                    finally: os.close(parent)
                # Re-inventory restored code before any scheduled SLL process can
                # run it. The final verification below also checks the restored
                # Asterisk schedule after it is enabled.
                self.verify_static(manifest)
                self.restore_user_jobs()
                self.verify()
                report={'ok':True,'automatic_activation_safe':False,'sls_root_jobs_disabled':True,
                        'message':'Static files restored. Admit an authenticated prior release before enabling SLL root jobs or activating its services.'}
                self.write_at(snapfd,'restore-result.json',json.dumps(report,sort_keys=True).encode())
                return report
            finally: os.close(blobs)
        finally: os.close(snapfd)

    def verify_static(self,manifest=None):
        manifest=self.load() if manifest is None else manifest
        current={}; self.total=0
        for path in (*TREES,*FIXED,*LINKS): self.inspect(path,records=current)
        if current!=manifest['records']: raise RecoveryError('Restored static inventory differs from original snapshot')
        return {'ok':True,'restored_static_verified':True}

    @_serialized_cron
    def verify(self):
        manifest=self.load()
        self.verify_static(manifest)
        if [line for line in self.user_cron().splitlines() if sls_user_job(line)]!=self.original_user_jobs():
            raise RecoveryError('Restored SLL user jobs differ from their original schedule')
        jobs=[line.decode('ascii') for line in self.cron().splitlines() if sls_cron_job(line)]
        descriptor=self.directory(self.snapshot,protected=True)
        try:
            try: marker,_=self.read_at(descriptor,'maintenance-restored.json',1024,True)
            except FileNotFoundError: marker=None
        finally: os.close(descriptor)
        if marker is None:
            if jobs: raise RecoveryError('SLL root jobs must remain disabled until authenticated activation')
        elif marker!=b'{"schema":1,"previous_release_approved":true}' or manifest.get('previous_activation_approval',{}).get('root_jobs')!=jobs:
            raise RecoveryError('Restored maintenance differs from the approved previous schedule')
        return {'ok':True,'snapshot_verified':True,'restored_static_verified':True,'automatic_activation_safe':False}

def verify_installed_cron(tables):
    """Require the exact silent five-job set while preserving unrelated data."""
    if not isinstance(tables,dict) or set(tables)!={'root','asterisk'}:
        raise RecoveryError('Invalid installed cron table inventory')
    for account,jobs in (('root',('maintenance','update')),
                         ('asterisk',('weather','scheduling','announcement_reconcile'))):
        body=tables[account]
        if not isinstance(body,bytes) or len(body)>1024*1024:
            raise RecoveryError('Installed cron table exceeds its bounded inspection size')
        expected=[(('17 * * * * ' if job=='update' else '* * * * * ')
            +'/usr/bin/python3 -I '+RUNTIME+'/sls_cron_runner.py '+job+' >/dev/null 2>&1').encode() for job in jobs]
        actual=[line for line in body.splitlines() if sls_cron_job(line,account)]
        if sorted(actual)!=sorted(expected):
            raise RecoveryError('The '+account+' SLL schedule is missing, duplicated, or differs from the canonical silent jobs')
    return {'ok':True,'installed_cron_verified':True}


def reconcile_cron(action, *, evidence=None, cron=None, cron_lock=native_cron_lock):
    """Inspect or remove only recognized module jobs under both native locks.

    Originals are durable before replacement. A failed second account restores
    the first only if its current bytes still match this attempt's output;
    administrator changes and recovery originals are retained for review.
    """
    if action not in ('preflight','remove','verify','verify-installed'):
        raise RecoveryError('Invalid coordinated cron action')
    backend=cron or Recovery.system_cron
    accounts=('root','asterisk')
    with cron_lock(accounts) as lease:
        def access(body=None,user='root'):
            if lease is not None:lease.check()
            value=backend(body,user=user)
            if lease is not None:lease.check()
            if body is None and (not isinstance(value,bytes) or len(value)>1024*1024):
                raise RecoveryError('The crontab exceeds its bounded inspection size')
            return value
        before={user:access(user=user) for user in accounts}
        if action=='verify-installed':return verify_installed_cron(before)
        after={user:b''.join(line for line in before[user].splitlines(keepends=True)
                            if not sls_cron_job(line.rstrip(b'\r\n'),user)) for user in accounts}
        changed=[user for user in accounts if before[user]!=after[user]]
        if action=='verify' and changed:
            raise RecoveryError('An SLL scheduled job remains in the '+', '.join(changed)+' crontab')
        if action!='remove' or not changed:
            return {'ok':True,'cron_action':action,'changed_accounts':[]}
        if evidence is None:
            raise RecoveryError('Cron removal requires a protected persistent uninstall transaction')
        parent=Recovery.directory(evidence,protected=True)
        name='cron-removal.'+uuid.uuid4().hex
        try:
            os.mkdir(name,0o700,dir_fd=parent);os.fsync(parent)
            directory=os.open(name,os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW|os.O_CLOEXEC,dir_fd=parent)
            archive=str(Path(evidence)/name)
            try:
                for user in accounts:
                    Recovery.write_at(directory,user+'.original',before[user])
                    Recovery.write_at(directory,user+'.expected',after[user])
                manifest={'schema':1,'accounts':{user:{'before_sha256':hashlib.sha256(before[user]).hexdigest(),
                    'expected_sha256':hashlib.sha256(after[user]).hexdigest()} for user in accounts}}
                Recovery.write_at(directory,'manifest.json',json.dumps(manifest,sort_keys=True).encode())
                if any(access(user=user)!=before[user] for user in accounts):
                    raise RecoveryError('An administrator changed a crontab during preparation; preserve '+archive)
                attempted=[]
                try:
                    for user in changed:
                        attempted.append(user)
                        access(after[user],user=user)
                        if access(user=user)!=after[user]:
                            raise RecoveryError('Cron replacement readback differs for '+user)
                    if any(access(user=user)!=after[user] for user in accounts):
                        raise RecoveryError('Cron schedules changed before final verification')
                except (RecoveryError,OSError,subprocess.SubprocessError) as error:
                    incomplete=[]
                    for user in reversed(attempted):
                        try:
                            current=access(user=user)
                            if current==before[user]:continue
                            if current!=after[user]:
                                incomplete.append(user);continue
                            access(before[user],user=user)
                            if access(user=user)!=before[user]:incomplete.append(user)
                        except (RecoveryError,OSError,subprocess.SubprocessError):incomplete.append(user)
                    message=('Cron rollback was incomplete for '+', '.join(incomplete) if incomplete
                             else 'Earlier replacements were rolled back')
                    raise RecoveryError(str(error)+'; '+message+'. Preserve '+archive) from error
                Recovery.write_at(directory,'result.json',b'{"ok":true,"removed":true}')
            finally:os.close(directory)
        finally:os.close(parent)
    return {'ok':True,'cron_action':action,'changed_accounts':changed,'cron_originals':archive}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--snapshot')
    parser.add_argument('--approval',help='root-protected previous execution approval established before mutation')
    parser.add_argument('--cron-action',choices=('preflight','remove','verify','verify-installed'))
    parser.add_argument('--cron-evidence',help='protected persistent uninstall transaction for original schedules')
    parser.add_argument('action',nargs='?',choices=('snapshot','restore','verify','service-state','restore-services','restore-maintenance','preflight-services','preflight-inventory'))
    args=parser.parse_args()
    if os.geteuid()!=0: raise RecoveryError('Static recovery requires root')
    # Do not load sibling Python or installed PHP. Installer must authenticate
    # this standalone helper before placing it in a protected bootstrap directory.
    here=Path(__file__).absolute(); parent=Recovery.directory(here.parent,protected=True)
    try: Recovery.read_at(parent,here.name,MAX_FILE,True)
    finally: os.close(parent)
    if args.cron_action:
        if args.snapshot or args.approval or args.action:parser.error('Cron inspection cannot include static recovery arguments')
        result=reconcile_cron(args.cron_action,evidence=args.cron_evidence)
    else:
        if not args.snapshot or not args.action or args.cron_evidence:parser.error('Static recovery requires --snapshot and an action')
        recovery=Recovery(args.snapshot,approval=args.approval)
        result=recovery.snapshot_create() if args.action=='snapshot' else getattr(recovery,args.action.replace('-','_'))()
    print(json.dumps(result,sort_keys=True))

if __name__=='__main__':
    try: main()
    except (RecoveryError,OSError,ValueError,KeyError,TypeError,subprocess.SubprocessError) as error:
        print('SLL static recovery failed: '+str(error),file=sys.stderr)
        sys.exit(1)
