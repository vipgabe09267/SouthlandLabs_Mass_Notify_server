def _protected_os_file(path):
    """Resolve only protected distribution files, including PHP alternatives."""
    path=Path(path)
    for _ in range(8):
        if not path.is_absolute() or '..' in path.parts:
            raise RecoveryError('Native cron coordination needs protected operating-system files')
        parent=Recovery.directory(path.parent,protected=True)
        try:
            info=os.stat(path.name,dir_fd=parent,follow_symlinks=False)
            if info.st_uid!=0 or info.st_nlink!=1:
                raise RecoveryError('Native cron coordination refused unsafe operating-system ownership')
            if stat.S_ISLNK(info.st_mode):
                target=os.readlink(path.name,dir_fd=parent)
                path=Path(target) if target.startswith('/') else path.parent/target
                continue
            if not stat.S_ISREG(info.st_mode) or info.st_mode&0o022 or not 0<info.st_size<=64*1024*1024:
                raise RecoveryError('Native cron coordination refused an unsafe operating-system file')
            return str(path)
        finally:os.close(parent)
    raise RecoveryError('Native cron coordination refused an interpreter link cycle')


def _native_cron_metadata_probe(command,environment):
    """Bound PHP startup separately from its later semaphore contention wait."""
    process=subprocess.Popen(command,stdin=subprocess.DEVNULL,stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,close_fds=True,start_new_session=True,cwd='/',env=environment)
    try:
        output,diagnostic=process.communicate(timeout=NATIVE_CRON_PHP_STARTUP_SECONDS)
    except BaseException:
        # runuser may have spawned PHP. Stop our whole fresh session so a
        # timed-out read-only metadata child cannot outlive the admission probe.
        try:os.killpg(process.pid,signal.SIGKILL)
        except ProcessLookupError:pass
        try:process.communicate(timeout=2)
        finally:
            if process.stdout is not None:process.stdout.close()
            if process.stderr is not None:process.stderr.close()
        raise
    return subprocess.CompletedProcess(command,process.returncode,output,diagnostic)


def _native_cron_php():
    """No FreePBX bootstrap, PHP configuration, web library or inherited secret."""
    account=pwd.getpwnam('asterisk')
    if account.pw_uid<=0 or os.geteuid() not in (0,account.pw_uid):
        raise RecoveryError('Native cron coordination requires root or the PBX runtime account')
    prefix=[] if os.geteuid()==account.pw_uid else [_protected_os_file('/usr/sbin/runuser'),'-u','asterisk','--']
    php=_protected_os_file('/usr/bin/php')
    environment={'PATH':'/usr/sbin:/usr/bin:/sbin:/bin','LANG':'C'}
    try:
        probe=_native_cron_metadata_probe([*prefix,php,'-n','-r',
            'echo json_encode(["extension_dir"=>ini_get("extension_dir"),"sysvsem"=>extension_loaded("sysvsem"),"posix"=>extension_loaded("posix")]);'],environment)
        if probe.returncode or not 0<len(probe.stdout)<=4096:
            raise RecoveryError('Native cron coordination could not identify the distribution PHP extension')
        metadata=json.loads(probe.stdout)
        if (not isinstance(metadata,dict) or set(metadata)!={'extension_dir','sysvsem','posix'}
                or not isinstance(metadata['extension_dir'],str)
                or any(type(metadata[name]) is not bool for name in ('sysvsem','posix'))):
            raise RecoveryError('Native cron coordination received invalid PHP extension metadata')
        extensions=[]
        for name in ('sysvsem','posix'):
            if metadata[name]:continue  # Source-built PHP may compile these in.
            directory=Path(metadata['extension_dir'])
            if not directory.is_absolute() or str(directory)!=metadata['extension_dir']:
                raise RecoveryError('Native cron coordination refused a noncanonical PHP extension directory')
            extensions.append(_protected_os_file(directory/(name+'.so')))
    except subprocess.TimeoutExpired as error:
        raise RecoveryError('Native cron PHP metadata startup timed out after '
            +str(NATIVE_CRON_PHP_STARTUP_SECONDS)+' seconds; no schedule was changed. '
            'Review system load and preserve the installation evidence before retrying.') from error
    except (OSError,ValueError,UnicodeError,subprocess.SubprocessError) as error:
        raise RecoveryError('Native cron coordination requires the protected PHP sysvsem and POSIX extensions') from error
    return [*prefix,php,'-n',*[option for path in extensions for option in ('-d','extension='+path)]],environment


class NativeCronLease:
    def __init__(self,process):self.process=process

    def check(self):
        if self.process.poll() is not None:
            raise RecoveryError('Native cron coordination exited; preserve recovery evidence before retrying')


@contextmanager
def native_cron_lock(accounts=('root','asterisk'),timeout=5):
    """Hold FreePBX's exact SysV semaphore identities using fixed runtime PHP.

    The child accepts account names and a lifetime pipe only, never a command,
    script path, configuration or executable payload from an administrator.
    """
    if (not isinstance(accounts,(list,tuple)) or not 1<=len(accounts)<=2
            or any(account not in ('root','asterisk') for account in accounts)
            or len(set(accounts))!=len(accounts) or type(timeout) not in (int,float)
            or not .05<=timeout<=10):
        raise RecoveryError('Invalid native cron coordination accounts or time bound')
    command,environment=_native_cron_php()
    process=None;ready=False
    try:
        process=subprocess.Popen([*command,'-r',_NATIVE_CRON_SEMAPHORE,str(timeout),*sorted(accounts)],
            stdin=subprocess.PIPE,stdout=subprocess.PIPE,stderr=subprocess.DEVNULL,
            close_fds=True,start_new_session=True,cwd='/',env=environment)
        with selectors.DefaultSelector() as selector:
            selector.register(process.stdout,selectors.EVENT_READ)
            readiness_wait=NATIVE_CRON_PHP_STARTUP_SECONDS+timeout
            if not selector.select(readiness_wait):
                raise RecoveryError('Native cron PHP readiness startup timed out after '
                    +str(readiness_wait)+' seconds; no schedule was changed. '
                    'Review system load and preserve the installation evidence before retrying.') from subprocess.TimeoutExpired(process.args,readiness_wait)
            ready=os.read(process.stdout.fileno(),32)==b'ready\n'
        if not ready:
            raise RecoveryError('Native cron coordination is unavailable or busy; no schedule was changed')
        lease=NativeCronLease(process);lease.check()
        yield lease
        lease.check()
    except (OSError,subprocess.SubprocessError) as error:
        raise RecoveryError('Native cron coordination failed; preserve the original schedules') from error
    finally:
        if process is not None:
            if process.stdin is not None:process.stdin.close()
            try:process.wait(timeout=2)
            except subprocess.TimeoutExpired:
                try:os.killpg(process.pid,signal.SIGTERM)
                except ProcessLookupError:pass
                try:process.wait(timeout=1)
                except subprocess.TimeoutExpired:
                    try:os.killpg(process.pid,signal.SIGKILL)
                    except ProcessLookupError:pass
                    process.wait(timeout=1)
            if process.stdout is not None:process.stdout.close()


def _serialized_cron(method):
    @wraps(method)
    def coordinated(self,*arguments,**keywords):
        with self.cron_guard():
            return method(self,*arguments,**keywords)
    return coordinated

